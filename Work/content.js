    /* =========================================================
       MEASURE
    ========================================================= */

    function measureItem() {

        if (
            !projectItems.length
        ) {

            return;

        }


        itemHeight =
            projectItems[0]
                .getBoundingClientRect()
                .height;

    }



    /* =========================================================
       MOVE LIST
    ========================================================= */

    function moveList(
        animate = true
    ) {

        if (
            !itemHeight
        ) {

            measureItem();

        }


        const windowHeight =
            projectWindow
                .getBoundingClientRect()
                .height;


        const center =
            (
                windowHeight -
                itemHeight
            ) / 2;


        const offset =
            center -
            (
                visualProject *
                itemHeight
            );


        if (
            animate
        ) {

            projectList.style.transition =
                "transform 0.52s cubic-bezier(0.16, 1, 0.3, 1)";

        }
        else {

            projectList.style.transition =
                "none";

        }


        projectList.style.transform =
            `translateY(${offset}px)`;


        updateOpacity();

    }



    /* =========================================================
       OPACITY
    ========================================================= */

    function updateOpacity() {

        projectItems.forEach(
            (item, index) => {

                const distance =
                    Math.abs(
                        index -
                        visualProject
                    );


                let opacity;


                if (
                    distance === 0
                ) {

                    opacity = 1;

                }

                else if (
                    distance === 1
                ) {

                    opacity = 0.48;

                }

                else if (
                    distance === 2
                ) {

                    opacity = 0.17;

                }

                else {

                    opacity = 0;

                }


                const title =
                    item.querySelector(
                        ".project-title"
                    );

                const number =
                    item.querySelector(
                        ".project-number"
                    );

                const line =
                    item.querySelector(
                        ".project-line"
                    );


                title.style.opacity =
                    opacity;


                number.style.opacity =
                    opacity *
                    0.7;


                line.style.opacity =
                    opacity *
                    0.55;


                item.classList.toggle(
                    "focus",
                    index === visualProject
                );


                item.classList.toggle(
                    "near",
                    distance === 1 ||
                    distance === 2
                );

            }
        );

    }



