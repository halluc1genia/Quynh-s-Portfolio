    /* =========================================================
       MOVE ONE STEP
    ========================================================= */

    function moveProject(
        direction
    ) {

        if (
            wheelLocked
        ) {

            return;

        }


        wheelLocked =
            true;


        visualProject +=
            direction;


        currentProject =
            (
                currentProject +
                direction +
                projects.length
            ) %
            projects.length;


        moveList(
            true
        );


        changeThumbnail(
            projects[
                currentProject
            ].images[0]
        );


        setTimeout(
            () => {

                if (
                    currentProject === 0 &&
                    visualProject >=
                    projects.length * 2
                ) {

                    visualProject =
                        projects.length;


                    moveList(
                        false
                    );

                }


                if (
                    currentProject ===
                    projects.length - 1 &&
                    visualProject <
                    projects.length
                ) {

                    visualProject =
                        projects.length * 2 -
                        1;


                    moveList(
                        false
                    );

                }


                wheelLocked =
                    false;

            },
            540
        );

    }



